// Pulls the printed card text out of design/SPEC.md (the source of truth) into
// src/ui/cardText.generated.ts so the in-game card popup always matches the spec.
import { readFileSync, writeFileSync } from 'node:fs';

const spec = readFileSync(new URL('../design/SPEC.md', import.meta.url), 'utf8').replace(/\r\n/g, '\n');
const lines = spec.split('\n');

const characters = {};
let current = null;
let inCharacters = false;
for (const line of lines) {
  if (line.startsWith('## ')) {
    inCharacters = line.startsWith('## 13. ');
    current = null;
    continue;
  }
  if (!inCharacters) continue;
  const m = /^### (.+?) \([A-Z]+ Rank\)\s*$/.exec(line);
  if (m) {
    current = m[1];
    characters[current] = [];
  } else if (current) {
    characters[current].push(line);
  }
}
for (const k of Object.keys(characters)) characters[k] = characters[k].join('\n').trim();

const start = lines.findIndex((l) => l.startsWith('## 13a.'));
const end = lines.findIndex((l) => l.startsWith('## 14.'));
const cards = {};
for (const para of lines.slice(start + 1, end).join('\n').split(/\n\s*\n/)) {
  const text = para.trim();
  if (!text || text === '---') continue;
  const m = /^\**([^*—]+?)\**\s+—/.exec(text.replace(/\n/g, ' '));
  if (m && m[1].length <= 40) cards[m[1].trim()] = text;
}

const out = `// GENERATED by scripts/extract-card-text.mjs from design/SPEC.md — do not edit by hand.
export const CHARACTER_TEXT: Record<string, string> = ${JSON.stringify(characters, null, 2)};

export const CARD_TEXT: Record<string, string> = ${JSON.stringify(cards, null, 2)};
`;
writeFileSync(new URL('../src/ui/cardText.generated.ts', import.meta.url), out);
console.log(`cardText: ${Object.keys(characters).length} characters, ${Object.keys(cards).length} cards`);
